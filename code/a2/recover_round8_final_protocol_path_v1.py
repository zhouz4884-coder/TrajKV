"""Recover metadata preparation after a relative CLI freeze-path failure.

Numerical/frozen sources and already-created metadata remain byte-identical.
Only exact regenerated bytes may reuse existing preparation files. No model,
parameter tuning or source membership changes are allowed.
"""
import argparse
import json
from pathlib import Path

import prepare_round8_final_protocol as original


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--freeze', type=Path, required=True)
    parser.add_argument('--expected-sha256', required=True)
    args = parser.parse_args()
    freeze = args.freeze.resolve()
    assert original.sha(freeze) == args.expected_sha256
    files = original.read(freeze)['frozen_files']
    assert all(original.sha(original.ROOT / row['path']) == row['sha256'] for row in files)
    reused = {}
    write_new = original.write_new

    def reuse_exact(path, value):
        path = Path(path)
        if path.is_file():
            expected = (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n').encode('utf-8')
            assert path.read_bytes() == expected, 'Preserve different existing metadata: ' + str(path)
            reused[str(path.relative_to(original.ROOT))] = original.sha(path)
        else:
            write_new(path, value)
    original.write_new = reuse_exact
    try:
        original.execute(freeze, args.expected_sha256)
    finally:
        original.write_new = write_new
    assert all(original.sha(original.ROOT / name) == digest for name, digest in reused.items())
    assert all(original.sha(original.ROOT / row['path']) == row['sha256'] for row in files)
    receipt = dict(status='PASS', schema='trajkv.round8.preparation-relative-path-recovery.v1',
        freeze_sha256=args.expected_sha256, original_preparer_sha256=original.sha(original.__file__),
        recovery_wrapper_sha256=original.sha(__file__), exact_existing_files_reused=reused,
        frozen_files_unchanged=True, original_preparer_unchanged=True,
        correction='Caller passes an absolute freeze path; original relative CLI path failed only during measurement config preparation',
        GPU_executed=False, parameter_or_variant_changes=False)
    write_new(original.ROOT / 'audit/a2/round8_final_protocol_path_recovery_v1.json', receipt)
    print(json.dumps(dict(status='PASS', exact_existing_files_reused=len(reused), frozen_files_unchanged=True)))


if __name__ == '__main__':
    main()
